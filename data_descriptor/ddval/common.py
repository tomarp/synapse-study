# ------------------------------------------------------------------------------------------------- loaders
def tsv(path: Path | str, **kw) -> pd.DataFrame:
    return pd.read_csv(BIDS / path if not Path(path).is_absolute() else path, sep="\t", na_values=["n/a"],
                       keep_default_na=False, **kw)


@lru_cache(maxsize=None)
def sessions() -> pd.DataFrame:
    rows = []
    for s in SUBS:
        d = tsv(f"{s}/{s}_sessions.tsv")
        d.insert(0, "participant_id", s)
        rows.append(d)
    out = pd.concat(rows, ignore_index=True)
    for c in ("session_start", "session_end"):
        out[c] = pd.to_datetime(out[c])
    return out


@lru_cache(maxsize=None)
def timeline() -> pd.DataFrame:
    t = tsv("derivatives/session_timeline/timeline.tsv")
    for c in ("onset_time", "offset_time"):
        t[c] = pd.to_datetime(t[c])
    return t


@lru_cache(maxsize=None)
def behaviour() -> pd.DataFrame:
    """All analysable trials (superseded runs removed) with participant, session, task and lighting."""
    rows = []
    for f in sorted(BIDS.glob("sub-*/ses-*/beh/*_beh.tsv")):
        sub, ses, task = re.search(r"(sub-P\d\d)_(ses-[AB])_task-([a-z]+)_beh", f.name).groups()
        d = tsv(f)
        d.insert(0, "task", task)
        d.insert(0, "session_id", ses)
        d.insert(0, "participant_id", sub)
        rows.append(d)
    b = pd.concat(rows, ignore_index=True)
    b = b[~b["superseded_run"].astype(bool)].copy()
    light = sessions().set_index(["participant_id", "session_id"])["light"]
    b["light"] = [light[k] for k in zip(b.participant_id, b.session_id)]
    return b


def physio(sub: str, ses: str, recording: str) -> pd.DataFrame | None:
    """Wrist signal with an absolute time column (s, Unix) built from the sidecar start time and sampling rate."""
    base = BIDS / sub / ses / "beh" / f"{sub}_{ses}_task-cogbattery_recording-{recording}_physio"
    if not base.with_suffix(".tsv.gz").exists():
        return None
    meta = json.loads(base.with_suffix(".json").read_text())
    with gzip.open(base.with_suffix(".tsv.gz"), "rt") as fh:
        d = pd.read_csv(fh, sep="\t", header=None, names=meta["Columns"], na_values=["n/a"])
    d.insert(0, "time_unix", meta["SYNAPSE_StartTimeUnix"] + np.arange(len(d)) / meta["SamplingFrequency"])
    d.attrs["fs"] = meta["SamplingFrequency"]
    return d


def vendor(sub: str, ses: str, desc: str) -> pd.DataFrame | None:
    f = BIDS / "derivatives" / "wristband_vendor_metrics" / sub / ses / f"{sub}_{ses}_task-cogbattery_desc-{desc}_timeseries.tsv"
    return tsv(f) if f.exists() else None


def facetemp(sub: str, ses: str) -> pd.DataFrame:
    return tsv(f"derivatives/facial_temperature/{sub}/{ses}/{sub}_{ses}_desc-facetemp_timeseries.tsv")


@lru_cache(maxsize=None)
def room() -> pd.DataFrame:
    return tsv("environment/room_monitor_1min.tsv")


def session_window(sub: str, ses: str) -> tuple[float, float]:
    """Unix start (end of T0 = baseline onset) and end (end of T3) of a session from the timeline."""
    t = timeline()
    t = t[(t.participant_id == sub) & (t.session_id == ses)]
    return float(t.loc[t.phase == "baseline", "onset_unix"].iloc[0]), float(t.loc[t.phase == "T3", "offset_unix"].iloc[0])


def median_iqr(x, fmt: str = "{:.1f}") -> str:
    x = np.asarray(x, dtype=float)
    x = x[np.isfinite(x)]
    q1, q2, q3 = np.percentile(x, [25, 50, 75])
    return f"{fmt.format(q2)} ({fmt.format(q1)}--{fmt.format(q3)})"
